/** Small numeric helpers for the analysis. */

export interface Distribution {
  readonly count: number;
  readonly p50: number | null;
  readonly p95: number | null;
  readonly p99: number | null;
  readonly max: number | null;
}

/** Nearest-rank percentile. `Infinity` entries stand for things that never happened. */
export const percentile = (sorted: ReadonlyArray<number>, p: number): number | null => {
  if (sorted.length === 0) return null;
  const rank = Math.ceil((p / 100) * sorted.length) - 1;
  return sorted[Math.min(sorted.length - 1, Math.max(0, rank))] ?? null;
};

export const distribution = (values: ReadonlyArray<number>): Distribution => {
  const sorted = [...values].sort((a, b) => a - b);
  return {
    count: sorted.length,
    p50: percentile(sorted, 50),
    p95: percentile(sorted, 95),
    p99: percentile(sorted, 99),
    max: sorted.at(-1) ?? null,
  };
};

export const groupCount = <A>(items: ReadonlyArray<A>, key: (item: A) => string) => {
  const counts: Record<string, number> = {};
  for (const item of items) {
    const k = key(item);
    counts[k] = (counts[k] ?? 0) + 1;
  }
  return counts;
};
