/**
 * Builds results/tables.md from the result files: every number REPORT.md quotes comes from here.
 *
 *   pnpm eval:tables [<chosen grading spec>]
 *
 * With a spec, also projects cost and load from that spec's measured cost per grade.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { templates } from "@goblins/templates";
import { Schema } from "effect";
import { type GradingCase, loadGradingDataset } from "../datasets/src/index.ts";
import { spentUsd } from "../src/client.ts";
import { goldItems, numberRecall } from "../src/extraction.ts";
import { CaseOutcome, summarize } from "../src/grading.ts";

const resultsDir = new URL("../results/", import.meta.url);
const read = (path: string): unknown => JSON.parse(readFileSync(new URL(path, resultsDir), "utf8"));

const pct = (n: number, d: number) => (d === 0 ? "–" : `${((100 * n) / d).toFixed(0)}%`);
const usd = (n: number, digits = 5) => `$${n.toFixed(digits)}`;
const row = (cells: ReadonlyArray<string | number>) => `| ${cells.join(" | ")} |`;
const table = (head: ReadonlyArray<string>, rows: ReadonlyArray<ReadonlyArray<string | number>>) =>
  [row(head), row(head.map(() => "---")), ...rows.map(row)].join("\n");

const out: Array<string> = [
  "# Eval tables",
  "",
  "Generated by `pnpm eval:tables` from `results/`. Do not edit by hand.",
  "",
];

// Grading ---------------------------------------------------------------------------------------

const GradingFile = Schema.Struct({
  spec: Schema.String,
  limit: Schema.NullOr(Schema.Number),
  outcomes: Schema.Array(CaseOutcome),
});

const dataset = loadGradingDataset();
const generated = dataset.cases.filter((c) => c.slice === "generated");
const flagOnly = generated.filter((c) => c.expected.scoreOn === "flag").length;

const loadRuns = (dir: string, repeats: boolean) =>
  (existsSync(new URL(`${dir}/`, resultsDir))
    ? readdirSync(new URL(`${dir}/`, resultsDir)).filter(
        (f) => f.endsWith(".json") && f.includes(".repeat-") === repeats,
      )
    : []
  )
    .map((f) => Schema.decodeUnknownSync(GradingFile)(read(`${dir}/${f}`)))
    .filter((r) => r.limit === null)
    .map((r) => ({ spec: r.spec, outcomes: r.outcomes }));
const runs = loadRuns("grading", false);
/** Second runs of the same requests (EVAL_REPEAT), to measure how much a model varies. */
const repeats = loadRuns("grading", true);
/** Earlier grading prompts, kept to show what each change did. */
const history = [
  {
    title: "first prompt (v1)",
    runs: loadRuns("grading-v1", false),
    note: "Run on an earlier 230-case version of the dataset; cases since renamed or removed are left out.",
  },
  {
    title: "second prompt (v2)",
    runs: loadRuns("grading-v2", false),
    note: "Same cases as the current prompt.",
  },
];

const summaryRow = (
  spec: string,
  cases: ReadonlyArray<GradingCase>,
  outcomes: ReadonlyArray<CaseOutcome>,
) => {
  const s = summarize(cases, outcomes);
  const graded = s.cases - s.failed;
  return [
    `\`${spec}\``,
    s.cases,
    pct(s.exact, s.scored),
    pct(s.lineAgreement * 1000, 1000),
    pct(s.flagged, graded),
    pct(s.autoCorrect, s.scored),
    `${s.autoUnder} / ${s.autoOver}`,
    `${s.flagRecall.did}/${s.flagRecall.should}`,
    `${s.falseFlags.did}/${s.falseFlags.shouldNot}`,
    s.failed,
    usd(s.meanCostUsd),
    `${(s.p50LatencyMs / 1000).toFixed(1)} / ${(s.p95LatencyMs / 1000).toFixed(1)}`,
    s.meanCompletionTokens.toFixed(0),
  ];
};

const head = [
  "Spec",
  "Cases",
  "Exact score",
  "Lines right",
  "Flagged",
  "Unflagged and right",
  "Unflagged under / over",
  "Should flag: flagged",
  "Should not flag: flagged",
  "Failed",
  "Cost per grade",
  "Latency p50 / p95 s",
  "Output tokens",
];

out.push(
  "## Grading",
  "",
  `${generated.length} generated cases, all reviewed. ${flagOnly} hinge on a digit or sign nobody can read for sure; they count toward the flag columns only, and the score columns are over the other ${generated.length - flagOnly}. Failed means the reply was unusable after three tries.`,
  "",
  "### Current prompt (v3)",
  "",
  table(
    head,
    runs.map((r) => summaryRow(r.spec, generated, r.outcomes)),
  ),
  "",
  ...history.flatMap((h) => [
    `### ${h.title[0]?.toUpperCase()}${h.title.slice(1)}`,
    "",
    h.note,
    "",
    table(
      head,
      h.runs.map((r) => summaryRow(r.spec, generated, r.outcomes)),
    ),
    "",
  ]),
  "",
);

// The same work in another slice (phone layout, or Kincaid's hand-drawn copy) next to the
// generated original, so the difference is the image and nothing else.
for (const slice of ["phone", "human"] as const) {
  const copies = dataset.cases.filter((c) => c.slice === slice);
  if (copies.length === 0) continue;
  const originals = copies.flatMap((c) => generated.filter((g) => `${g.id}-${slice}` === c.id));
  const graded = runs.filter((r) => r.outcomes.some((o) => copies.some((c) => c.id === o.caseId)));
  out.push(
    `### ${slice === "phone" ? "Phone layout" : "Hand-drawn"} copies against their generated originals`,
    "",
    table(
      ["Spec", "Cases", "Exact, original", "Exact, copy", "Flagged, original", "Flagged, copy"],
      graded.map((r) => {
        const a = summarize(originals, r.outcomes);
        const b = summarize(copies, r.outcomes);
        return [
          `\`${r.spec}\``,
          copies.length,
          pct(a.exact, a.scored),
          pct(b.exact, b.scored),
          pct(a.flagged, a.cases - a.failed),
          pct(b.flagged, b.cases - b.failed),
        ];
      }),
    ),
    "",
  );
}

if (repeats.length > 0) {
  out.push(
    "### Run-to-run variation",
    "",
    "The same requests sent again. Temperature is 0, but providers don't guarantee identical replies.",
    "",
    table(
      [
        "Spec",
        "Cases",
        "Same total, both runs",
        "Same flag, both runs",
        "Exact, first run",
        "Exact, second run",
      ],
      repeats.flatMap((second) => {
        const first = runs.find((r) => r.spec === second.spec);
        if (first === undefined) return [];
        const a = new Map(first.outcomes.map((o) => [o.caseId, o]));
        const both = second.outcomes.flatMap((o) => {
          const x = a.get(o.caseId);
          return x?._tag === "Graded" &&
            o._tag === "Graded" &&
            generated.some((c) => c.id === o.caseId)
            ? [[x, o] as const]
            : [];
        });
        return [
          [
            `\`${second.spec}\``,
            both.length,
            pct(both.filter(([x, y]) => x.points === y.points).length, both.length),
            pct(both.filter(([x, y]) => x.flagged === y.flagged).length, both.length),
            pct(
              summarize(generated, first.outcomes).exact,
              summarize(generated, first.outcomes).scored,
            ),
            pct(
              summarize(generated, second.outcomes).exact,
              summarize(generated, second.outcomes).scored,
            ),
          ],
        ];
      }),
    ),
    "",
  );
}

const tags = [...new Set(generated.flatMap((c) => c.tags))].sort();
out.push(
  "### Exact score by tag",
  "",
  table(
    [
      "Spec",
      ...tags.map(
        (t) =>
          `${t} (${generated.filter((c) => c.tags.includes(t) && c.expected.scoreOn === "points").length})`,
      ),
    ],
    runs.map((r) => {
      const byId = new Map(r.outcomes.map((o) => [o.caseId, o]));
      return [
        `\`${r.spec}\``,
        ...tags.map((t) => {
          const cs = generated.filter((c) => c.tags.includes(t) && c.expected.scoreOn === "points");
          const right = cs.filter((c) => {
            const o = byId.get(c.id);
            return o?._tag === "Graded" && o.points === c.expectedPoints;
          }).length;
          return pct(right, cs.length);
        }),
      ];
    }),
  ),
  "",
);

// Extraction ------------------------------------------------------------------------------------

const extractionTable = (file: string, title: string, intro: string) => {
  if (!existsSync(new URL(file, resultsDir))) return;
  const ExtractionRun = Schema.Struct({
    model: Schema.String,
    templateId: Schema.String,
    ok: Schema.Boolean,
    costUsd: Schema.optional(Schema.Number),
    completionTokens: Schema.optional(Schema.Number),
    latencyMs: Schema.optional(Schema.NullOr(Schema.Number)),
    extraction: Schema.optional(
      Schema.Struct({
        _tag: Schema.String,
        problems: Schema.optional(
          Schema.Array(
            Schema.Struct(
              { label: Schema.String, answerKey: Schema.String },
              { key: Schema.String, value: Schema.Unknown },
            ),
          ),
        ),
      }),
    ),
    score: Schema.optional(
      Schema.NullOr(
        Schema.Struct({
          extraLabels: Schema.Array(Schema.String),
          items: Schema.Array(
            Schema.Struct({
              found: Schema.Boolean,
              textSimilarity: Schema.Number,
              followThroughInRubric: Schema.optional(Schema.Boolean),
            }),
          ),
          problems: Schema.Array(
            Schema.Struct({
              diagramOk: Schema.Boolean,
              diagramNumberRecall: Schema.optional(Schema.Number),
              crossPageOk: Schema.optional(Schema.Boolean),
            }),
          ),
          dependencies: Schema.Struct({
            gold: Schema.Number,
            found: Schema.Number,
            correct: Schema.Number,
          }),
        }),
      ),
    ),
  });
  const extraction = Schema.decodeUnknownSync(Schema.Array(ExtractionRun))(read(file));
  const specs = [...new Set(extraction.map((r) => r.model))];
  const goldCount = templates.reduce((sum, t) => sum + goldItems(t).length, 0);
  out.push(
    title,
    "",
    intro.replace("{items}", String(goldCount)),
    "",
    table(
      [
        "Spec",
        "Items found",
        "Invented items",
        "Text similarity",
        "Key numbers match",
        "Figures described",
        "Figure numbers kept",
        "Dependencies linked",
        "Extra links",
        "Follow-through in rubric",
        "Failed",
        "Cost per worksheet",
        "Mean latency s",
      ],
      specs.map((spec) => {
        const mine = extraction.filter((r) => r.model === spec);
        const ok = mine.filter((r) => r.ok && r.score !== undefined && r.score !== null);
        const items = ok.flatMap((r) => r.score?.items ?? []);
        const found = items.filter((i) => i.found);
        const problems = ok.flatMap((r) => r.score?.problems ?? []);
        const figures = problems.flatMap((p) =>
          p.diagramNumberRecall === undefined ? [] : [p.diagramNumberRecall],
        );
        const dependent = found.filter((i) => i.followThroughInRubric !== undefined);
        let keyMatch = 0;
        for (const r of ok) {
          const template = templates.find((t) => t.id === r.templateId);
          if (template === undefined) continue;
          for (const g of goldItems(template)) {
            const got = r.extraction?.problems?.find((p) => p.label === g.label);
            if (got !== undefined && numberRecall(g.answer, got.answerKey) === 1) keyMatch++;
          }
        }
        const deps = ok.reduce(
          (acc, r) => ({
            gold: acc.gold + (r.score?.dependencies.gold ?? 0),
            found: acc.found + (r.score?.dependencies.found ?? 0),
            correct: acc.correct + (r.score?.dependencies.correct ?? 0),
          }),
          { gold: 0, found: 0, correct: 0 },
        );
        const latencies = ok.flatMap((r) => (typeof r.latencyMs === "number" ? [r.latencyMs] : []));
        const cost = mine.reduce((sum, r) => sum + (r.costUsd ?? 0), 0) / Math.max(1, ok.length);
        return [
          `\`${spec}\``,
          `${found.length}/${goldCount}`,
          ok.reduce((sum, r) => sum + (r.score?.extraLabels.length ?? 0), 0),
          (found.reduce((sum, i) => sum + i.textSimilarity, 0) / Math.max(1, found.length)).toFixed(
            3,
          ),
          `${keyMatch}/${found.length}`,
          `${problems.filter((p) => p.diagramOk).length}/${problems.length}`,
          pct(figures.reduce((a, b) => a + b, 0) * 100, figures.length * 100),
          `${deps.correct}/${deps.gold}`,
          deps.found - deps.correct,
          `${dependent.filter((i) => i.followThroughInRubric).length}/${dependent.length}`,
          mine.length - ok.length,
          usd(cost, 4),
          latencies.length === 0
            ? "–"
            : (latencies.reduce((a, b) => a + b, 0) / latencies.length / 1000).toFixed(0),
        ];
      }),
    ),
    "",
  );
};

extractionTable(
  "extraction.json",
  "## Extraction",
  `Four worksheets, {items} gradable items. "Key numbers match" counts items whose extracted answer key contains every number in the hand-checked key's answer; a mismatch can still be a correct key written differently, so REPORT.md lists the ones read by hand.`,
);
extractionTable(
  "extraction-previous-pages.json",
  "### Extraction on the first page render, with the reasoning-effort sweep",
  "The same worksheets before #14 re-rendered each last page, scored against today's keys. `@low`, `@medium` and `@high` set the reasoning effort; without one the model's default applies. Failed runs timed out at 120 s.",
);

// Chat ------------------------------------------------------------------------------------------

if (existsSync(new URL("chat/", resultsDir))) {
  const ChatRun = Schema.Struct({
    spec: Schema.String,
    caseId: Schema.String,
    ok: Schema.Boolean,
    problems: Schema.Array(Schema.String),
    costUsd: Schema.Number,
  });
  const chat = readdirSync(new URL("chat/", resultsDir))
    .filter((f) => f.endsWith(".json"))
    .sort()
    .flatMap((f) =>
      Schema.decodeUnknownSync(Schema.Array(ChatRun))(read(`chat/${f}`)).map((r) => ({
        ...r,
        spec: f.includes(".repeat-")
          ? `${r.spec} (repeat ${f.split(".repeat-")[1]?.replace(".json", "")})`
          : r.spec,
      })),
    );
  const specs = [...new Set(chat.map((r) => r.spec))];
  const caseIds = [...new Set(chat.map((r) => r.caseId))];
  out.push(
    "## Chat editing",
    "",
    table(
      ["Spec", "Passed", ...caseIds, "Cost per message"],
      specs.map((spec) => {
        const mine = chat.filter((r) => r.spec === spec);
        return [
          `\`${spec}\``,
          `${mine.filter((r) => r.ok).length}/${mine.length}`,
          ...caseIds.map((id) => (mine.find((r) => r.caseId === id)?.ok ? "pass" : "fail")),
          usd(mine.reduce((sum, r) => sum + r.costUsd, 0) / Math.max(1, mine.length), 4),
        ];
      }),
    ),
    "",
  );
}

// Projections ------------------------------------------------------------------------------------

const chosen = process.argv[2];
const chosenRun = runs.find((r) => r.spec === chosen);
if (chosen !== undefined && chosenRun === undefined) {
  console.error(`No full grading run for ${chosen}`);
  process.exit(1);
}
if (chosenRun !== undefined) {
  const s = summarize(generated, chosenRun.outcomes);
  const graded = chosenRun.outcomes.flatMap((o) => (o._tag === "Graded" ? [o] : []));
  const promptTokens = graded.reduce((sum, o) => sum + o.promptTokens, 0) / graded.length;
  const completionTokens = graded.reduce((sum, o) => sum + o.completionTokens, 0) / graded.length;
  // The PRD's teacher: 130 students, one 10-problem assignment a week.
  const weeksPerMonth = 52 / 12;
  const gradesPerStudentMonth = 10 * weeksPerMonth;
  const studentsPerTeacher = 130;
  // Setup per assignment: one extraction and about five chat messages, at the measured costs.
  const setupPerAssignment = 0.006 + 5 * 0.002;
  const perTeacher =
    studentsPerTeacher * gradesPerStudentMonth * s.meanCostUsd + weeksPerMonth * setupPerAssignment;
  out.push(
    "## Cost and load projections",
    "",
    `From \`${chosen}\`: ${usd(s.meanCostUsd)} per grade on average, retries included, with ${promptTokens.toFixed(0)} prompt and ${completionTokens.toFixed(0)} output tokens per call. A student does one 10-problem assignment a week (${gradesPerStudentMonth.toFixed(1)} grades a month); a teacher has ${studentsPerTeacher} students and sets up one assignment a week (${usd(setupPerAssignment, 3)} each for extraction and five chat messages).`,
    "",
    `Cost per teacher per month: **${usd(perTeacher, 2)}** (target about $5).`,
    "",
    "Peak load assumes the PRD's testing day: every student in one 30-minute window, 10 submissions each. Spread over a school's class periods, the peak is a fraction of this.",
    "",
    table(
      [
        "Students",
        "Teachers",
        "Grades a month",
        "Model cost a month",
        "Peak grades/s",
        "Peak tokens/min",
      ],
      [1_000, 10_000, 100_000, 1_000_000].map((students) => {
        const peak = (students * 10) / (30 * 60);
        return [
          students.toLocaleString("en-US"),
          Math.round(students / studentsPerTeacher).toLocaleString("en-US"),
          Math.round(students * gradesPerStudentMonth).toLocaleString("en-US"),
          `$${Math.round((students / studentsPerTeacher) * perTeacher).toLocaleString("en-US")}`,
          peak.toFixed(1),
          `${((peak * 60 * (promptTokens + completionTokens)) / 1e6).toFixed(1)}M`,
        ];
      }),
    ),
    "",
  );
}

out.push("## Spend", "", `Every real call the evals made so far: ${usd(spentUsd(), 2)}.`, "");

writeFileSync(new URL("tables.md", resultsDir), `${out.join("\n")}\n`);
console.log("Wrote results/tables.md");
